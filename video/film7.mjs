// film7.mjs: the phone app (the Capacitor build served by preview.mjs) on an iPhone-sized screen
import { chromium, devices } from '/opt/npm-tools/node_modules/playwright/index.mjs';
import { mkdirSync, writeFileSync, rmSync } from 'fs';
const S = 'http://localhost:8097', APP = 'http://localhost:8100', OUT = '/tmp/video/scenes/t18-mobile/';
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const call = async (m, p, b, t, acc) => { const r = await fetch(S + p, { method: m, headers: { 'Content-Type': 'application/json', ...(t ? { Authorization: 'Bearer ' + t } : {}), ...(acc ? { 'X-Account': String(acc) } : {}) }, body: b ? JSON.stringify(b) : undefined }); const x = await r.text(); if (!r.ok) throw new Error(p + r.status + x); return x ? JSON.parse(x) : {}; };
const email = `kostas.phone.${Date.now()}@demo.example`;
const reg = await call('POST', '/api/auth/register', { email, password: 'password-123' });
const acc = await call('GET', '/api/account', null, reg.token);
await call('POST', '/api/wallet/deposits', { amount: '5000', reference: 'phone' + Date.now() }, reg.token, acc.number);
await call('POST', '/api/orders', { symbol: 'BTCUSD', side: 'buy', lots: 0.05 }, reg.token, acc.number);
const e = await call('POST', '/api/orders', { symbol: 'ETHUSD', side: 'buy', lots: 0.3 }, reg.token, acc.number);
await sleep(4000); await call('POST', '/api/positions/' + e.position.id + '/close', {}, reg.token, acc.number);
const e2 = await call('POST', '/api/orders', { symbol: 'BTCUSD', side: 'sell', lots: 0.02 }, reg.token, acc.number);
await sleep(3000); await call('POST', '/api/positions/' + e2.position.id + '/close', {}, reg.token, acc.number);
const b = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox'] });
const ctx = await b.newContext({ ...devices['iPhone 13'], deviceScaleFactor: 2, defaultBrowserType: undefined });
const p = await ctx.newPage();
await p.goto(APP + '/');
await p.locator('input[autocomplete~=username]').fill(email);
await p.locator('input[autocomplete=current-password]').fill('password-123');
await p.locator('input[autocomplete=current-password]').press('Enter');
await p.locator('.acc-btn').first().waitFor({ timeout: 10000 }); await sleep(2500);
rmSync(OUT, { recursive: true, force: true }); mkdirSync(OUT, { recursive: true });
const frames = []; let stop = false;
const loop = (async () => { while (!stop) { const t = Date.now(); try { frames.push({ t, buf: await p.screenshot({ type: 'jpeg', quality: 92 }) }); } catch { await sleep(30); } } })();
const menu = async (label) => { await p.locator('.acc-btn').first().click(); await sleep(600); await p.locator('.acc-action', { hasText: label }).first().click(); await sleep(1300); };
await sleep(2500);
await p.locator('#mnav button[data-m=positions]').click(); await sleep(2800);
await menu('Money manager'); await sleep(2500); await p.keyboard.press('Escape'); await sleep(600);
await menu('Statements'); await sleep(1200);
await p.getByRole('button', { name: 'Print / Save as PDF' }).click(); await sleep(3200);
stop = true; await loop;
let list = '';
frames.forEach((f, i) => { const file = `f${String(i).padStart(5, '0')}.jpg`; writeFileSync(OUT + file, f.buf); list += `file '${file}'\nduration ${(i + 1 < frames.length ? (frames[i + 1].t - f.t) / 1000 : 0.1).toFixed(3)}\n`; });
list += `file 'f${String(frames.length - 1).padStart(5, '0')}.jpg'\n`;
writeFileSync(OUT + 'list.txt', list);
console.log('t18-mobile', frames.length, 'frames', ((frames.at(-1).t - frames[0].t) / 1000).toFixed(1) + 's');
await b.close();
